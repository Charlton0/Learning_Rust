fn main() {
    println!("Hello, world!");
    println!("I am learning rust");
    println!("It's awesome"); // println() can be used multiple times and for each it inserts a new line
    print!("I will insert a new line\n"); //to insert a new line manually with print!() use \n
}

//fn is a reserved word used to define a function
//main() is a function
//println!() is a macro used to display output(printing texts)
//print!() is similar to println() macro only that it does not insert a new line after, it prints on the same line

 